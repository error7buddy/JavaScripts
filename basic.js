// Addition
const sum = 2 + 3;
console.log(sum); // Output: 5

// Subtraction
const difference = 5 - 2;
console.log(difference); // Output: 3

// Multiplication
const product = 4 * 3;
console.log(product); // Output: 12

// Division
const quotient = 10 / 2;
console.log(quotient); // Output: 5

// Modulo (Remainder)
const remainder = 10 % 3;
console.log(remainder); // Output: 1